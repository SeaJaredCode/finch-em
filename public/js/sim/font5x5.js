/** Columns (each an array of 5 bits, top to bottom) for a glyph, trimmed of empty edge columns. */
function glyphColumns(ch) {
  const rows = GLYPHS[ch.toUpperCase()] || GLYPHS['?'];
  const cols = [];
  for (let c = 0; c < 5; c++) cols.push(rows.map((row) => (row[c] === '1' ? 1 : 0)));
  if (ch === ' ') return [cols[0], cols[0]];
  let first = 0;
  let last = 4;
  while (first < 4 && cols[first].every((b) => b === 0)) first++;
  while (last > first && cols[last].every((b) => b === 0)) last--;
  return cols.slice(first, last + 1);
}

/** Column stream for scrolling text: 5 blank lead-in columns, glyphs separated by one blank column. */
export function textToColumns(text) {
  const blank = [0, 0, 0, 0, 0];
  const out = [blank, blank, blank, blank, blank];
  for (const ch of String(text)) {
    out.push(...glyphColumns(ch));
    out.push(blank);
  }
  return out;
}

/** A 25-entry row-major frame showing columns [offset, offset+5). */
export function frameAt(columns, offset) {
  const frame = new Array(25).fill(0);
  for (let c = 0; c < 5; c++) {
    const col = columns[offset + c];
    if (!col) continue;
    for (let r = 0; r < 5; r++) frame[r * 5 + c] = col[r];
  }
  return frame;
}
